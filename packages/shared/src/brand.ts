/**
 * Реестр брендов для CRM.
 *
 * Система разворачивается экземплярами на клиента: код один, образ один,
 * а различия живут в `.env` экземпляра — переменная `BRAND_PROFILE`. Сайт
 * умел это с самого начала (apps/site-westauto/src/content/brands/), CRM —
 * нет, и клиент видел чужое имя ровно там, где складывается первое
 * впечатление: на экране входа.
 *
 * Реестр лежит в shared, а не в API или в приложении, потому что нужен обоим:
 * API отдаёт запись наружу (`GET /api/brand`), приложение её показывает.
 * Если бы запись жила в API, у приложения не было бы её типа; если бы в
 * приложении — API нечего было бы отдавать.
 *
 * Полей здесь ровно столько, сколько нужно CRM. Контакты, логотипы, палитра
 * сайта и прочее богатство профиля сайта сюда не переносятся: у CRM один
 * брендированный экран и одна шапка, а лишнее поле — это поле, которое
 * однажды разойдётся с сайтом и начнёт врать.
 */

/**
 * Знак бренда в шапке и на экране входа.
 *
 * Строкой, а не компонентом: shared собирается без React и работает в том
 * числе на сервере. Сопоставление строки с картинкой — дело приложения
 * (apps/app/src/components/Icons.tsx).
 */
export type BrandMark = 'key' | 'ship';

export interface CrmBrand {
  /** Значение `BRAND_PROFILE`, по которому профиль выбирается. */
  readonly id: string;

  /** Полное название — для подвала и заголовков. */
  readonly name: string;

  /**
   * Хвост названия, который вёрстка выделяет курсивом (`Авто<em>Ключ</em>`).
   *
   * Храним хвост, а не две половины: половины рано или поздно разойдутся с
   * полным именем, а хвост от него неотделим — он обязан быть его концом,
   * и `splitBrandName()` это проверяет. У односоставного имени хвоста нет —
   * `null`, а не пустая строка: «нет выделения» и «выделить ничего» это
   * разные вещи только на вид, но пустая строка прячет опечатку.
   */
  readonly nameEmphasis: string | null;

  /** Знак рядом с названием. */
  readonly mark: BrandMark;

  /**
   * Акцентный цвет (`--accent`) или `null` — «оставить цвет темы».
   *
   * `null` нужен не для красоты: у АвтоКлюча акцент задан в app.css дважды —
   * свой для тёмной темы и свой для светлой. Один hex не может быть обоими,
   * и жёсткое значение здесь испортило бы светлую тему живого экземпляра.
   * Профиль, которому своя палитра не нужна, ставит `null` и получает ровно
   * то, что было до появления реестра.
   */
  readonly accent: string | null;
  /**
   * Цвет текста на акцентных кнопках или `null` — «оставить цвет темы».
   *
   * Отдельно от accent потому, что контраст зависит от самого акцента:
   * на тёплом золотом АвтоКлюча читается тёмный текст, на зелёном — белый.
   * Одним полем это не выражается, а ошибка видна сразу на каждой кнопке.
   */
  readonly accentInk: string | null;

  /** Фон тёмной панели входа (`--ink`) или `null` — «оставить цвет темы». */
  readonly darkPanel: string | null;

  /** Короткая фраза на экране входа — одна мысль, в кавычках-ёлочках. */
  readonly quote: string;

  /** Абзац под фразой: чем система занимается. Два-три предложения. */
  readonly intro: string;

  /**
   * Подпись в подвале экрана входа. `{year}` подставляется текущим годом —
   * см. `brandFooter()`.
   *
   * Строкой целиком, а не «названием плюс примечанием»: у следующего
   * экземпляра подпись может оказаться на другом языке или с другой
   * структурой, и собирать её из кусков тогда нечем.
   */
  readonly footer: string;
}

