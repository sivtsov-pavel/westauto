/** Профиль по умолчанию: без `BRAND_PROFILE` экземпляр работает как раньше. */
export const DEFAULT_CRM_BRAND = westautoCrmBrand;

export const CRM_BRANDS: Record<string, CrmBrand> = {
  [westautoCrmBrand.id]: westautoCrmBrand,
  [larusCrmBrand.id]: larusCrmBrand,
};

/**
 * Профиль по значению `BRAND_PROFILE`.
 *
 * Опечатка в `.env` не должна ронять вход в систему: отдаём прежний бренд и
 * пишем предупреждение. Падение здесь означало бы, что из-за лишней буквы в
 * переменной никто не может войти в CRM, — цена ошибки несопоставима.
 */
export function resolveCrmBrand(profile: string | null | undefined): CrmBrand {
  const id = profile?.trim();
  if (!id) return DEFAULT_CRM_BRAND;

  const brand = CRM_BRANDS[id];
  if (!brand) {
    console.warn(`[brand] профиль «${id}» неизвестен — беру ${DEFAULT_CRM_BRAND.id}`);
    return DEFAULT_CRM_BRAND;
  }
  return brand;
}

/**
 * Название, разобранное на обычную часть и выделяемый хвост.
 *
 * Хвост, который не является концом имени, — опечатка в профиле. Молча
 * показывать такое имя нельзя (получится «АвтоКлючКлюч» или обрезок),
 * поэтому выделение в этом случае просто не применяется.
 */
export function splitBrandName(brand: CrmBrand): { lead: string; emphasis: string | null } {
  const { name, nameEmphasis } = brand;
  if (!nameEmphasis || !name.endsWith(nameEmphasis) || name === nameEmphasis) {
    return { lead: name, emphasis: null };
  }
  return { lead: name.slice(0, name.length - nameEmphasis.length), emphasis: nameEmphasis };
}

/** Подпись подвала с подставленным годом. */
export function brandFooter(brand: CrmBrand, year: number): string {
  return brand.footer.replace('{year}', String(year));
}
