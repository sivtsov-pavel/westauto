// ─── Мелкие блоки ───────────────────────────────────────────────────────────

function Card({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="card docs-card">
      <h2 className="docs-card-title">{title}</h2>
      {children}
    </section>
  );
}

function Steps({ items }: { items: [string, string][] }) {
  return (
    <ol className="docs-steps">
      {items.map(([title, text]) => (
        <li key={title}>
          <strong>{title}</strong>
          <span className="muted">{text}</span>
        </li>
      ))}
    </ol>
  );
}

function Rows({ items }: { items: [ReactNode, string][] }) {
  return (
    <dl className="docs-rows">
      {items.map(([term, description], index) => (
        <div key={index}>
          <dt>{term}</dt>
          <dd>{description}</dd>
        </div>
      ))}
    </dl>
  );
}
