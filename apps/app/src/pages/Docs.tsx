import { useState, type ReactNode } from 'react';
import type { Role } from '@avtoklyuch/shared';
import { useAuth } from '@/state/auth';

/**
 * Документация внутри приложения.
 *
 * Лежит здесь, а не в файле на сервере, намеренно: менеджер читает её в тот
 * момент, когда застрял на конкретном экране, и открывать ради этого
 * репозиторий он не будет. Текст описывает только то, что действительно
 * реализовано — обещаний на будущее здесь нет.
 */

type Tab = 'start' | 'manager' | 'agent' | 'admin' | 'faq';

const TABS: { id: Tab; label: string; roles?: Role[] }[] = [
  { id: 'start', label: 'С чего начать' },
  { id: 'agent', label: 'Агенту', roles: ['agent'] },
  { id: 'manager', label: 'Менеджеру', roles: ['admin', 'manager'] },
  { id: 'admin', label: 'Администратору', roles: ['admin'] },
  { id: 'faq', label: 'Частые вопросы' },
];

export function Docs() {
  const { user } = useAuth();
  const role = user?.role ?? 'manager';
  const isAdmin = role === 'admin';
  const isAgent = role === 'agent';
  const [tab, setTab] = useState<Tab>('start');

  const visibleTabs = TABS.filter((t) => !t.roles || t.roles.includes(role));

  return (
    <>
      <header className="topbar">
        <div>
          <div style={{ fontSize: 18, fontWeight: 600 }}>Документация</div>
          <div className="muted" style={{ fontSize: 12.5, marginTop: 2 }}>
            Как пользоваться системой — коротко и по делу
          </div>
        </div>
      </header>

      <div className="page">
        <div className="docs-tabs" role="tablist" aria-label="Разделы документации">
          {visibleTabs.map((item) => (
            <button
              key={item.id}
              type="button"
              role="tab"
              aria-selected={tab === item.id}
              className="docs-tab"
              onClick={() => setTab(item.id)}
            >
              {item.label}
            </button>
          ))}
        </div>

        <div className="docs-body">
          {tab === 'start' && <StartSection isAdmin={isAdmin} isAgent={isAgent} />}
          {tab === 'agent' && isAgent && <AgentSection />}
          {tab === 'manager' && !isAgent && <ManagerSection />}
          {tab === 'admin' && isAdmin && <AdminSection />}
          {tab === 'faq' && <FaqSection isAdmin={isAdmin} />}
        </div>
      </div>
    </>
  );
}

