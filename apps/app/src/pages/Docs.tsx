/**
 * Запуск тура из документации.
 *
 * Предложение при первом входе человек мог отклонить или пройти тур
 * невнимательно. Искать, где он включается, никто не станет — поэтому
 * кнопка лежит там, куда идут за объяснениями.
 */
function TourCard() {
  const { start, steps } = useTour();
  if (steps.length === 0) return null;

  return (
    <Card title="Тур по системе">
      <p>
        Проведём по разделам и на каждом скажем, зачем он нужен — {steps.length}{' '}
        {stepsWord(steps.length)}, прервать можно в любой момент.
      </p>
      <button type="button" className="btn btn-primary btn-sm" onClick={start}>
        Пройти тур заново
      </button>
    </Card>
  );
}

/** «шаг», «шага» или «шагов» — без этого выйдет «7 шаг(ов)» */
function stepsWord(count: number): string {
  const tail = count % 100;
  if (tail >= 11 && tail <= 14) return 'шагов';
  const last = count % 10;
  if (last === 1) return 'шаг';
  if (last >= 2 && last <= 4) return 'шага';
  return 'шагов';
}

