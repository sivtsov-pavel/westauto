import type { Permissions, Role } from '@avtoklyuch/shared';

/**
 * Шаги тура по системе.
 *
 * Объявлены так же, как пункты меню в components/Layout.tsx: `roles` и
 * `needs` с правом из packages/shared/src/roles.ts. Это не дублирование от
 * лени — иначе тур однажды покажет пальцем на раздел, которого у человека
 * нет, и первое знакомство с системой начнётся с «а у меня такого нету».
 * Фильтрует их та же логика, что и навигацию (см. state/tour.tsx).
 *
 * Текст — одна мысль на шаг. Объясняем смысл раздела, а не называем кнопки:
 * названия человек прочитает и сам, а зачем ему эта страница — нет.
 */

export interface TourStep {
  /** Нужен только для ключей в React и для сохранения прогресса */
  id: string;
  /** Маршрут, на который тур переводит перед показом шага */
  route: string;
  /** Значение атрибута data-tour у элемента, который подсвечиваем */
  target: string;
  title: string;
  text: string;
  /** Право, открывающее раздел — то же, что у пункта меню */
  needs?: keyof Permissions;
  /** Роли, которым шаг адресован (если раздел виден не по праву, а по роли) */
  roles?: Role[];
}

