/**
 * Метка учебной записи.
 *
 * Отдельным компонентом, а не инлайном в пяти местах: формулировка и
 * подсказка должны быть одинаковыми на доске, в таблицах и в карточке. Пять
 * копий «демо» / «учебное» / «тест» разойдутся, и человек перестанет верить
 * метке — а именно ей он и решает, настоящие перед ним деньги или нет.
 *
 * Неброско по стилю (серый badge-muted, не цветной): учебных записей на
 * стенде много, и красная метка на каждой строке превратила бы список в
 * предупреждение, которое перестают замечать.
 */
export function DemoBadge({ className }: { className?: string }) {
  return (
    <span
      className={`badge badge-muted${className ? ` ${className}` : ''}`}
      title="Учебная запись — заведена для демонстрации, не настоящая сделка. Скрыть все учебные записи можно в «Настройках»."
    >
      учебные
    </span>
  );
}
