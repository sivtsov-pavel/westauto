-- ─────────────────────────────────────────────────────────────────────────────
-- 008 — один человек = один телефон, как бы его ни записали
--
-- Прошлый индекс сравнивал все цифры номера подряд, и +380 67 111-22-33
-- расходился с 0671112233 — хотя это один и тот же человек. Дубль клиента
-- разваливает и историю сделок, и счёт вернувшихся: второй приход выглядит
-- как новый клиент.
--
-- Сравниваем по последним девяти цифрам: столько в национальном номере, и
-- код страны с ведущим нулём на них уже не влияет.
-- ─────────────────────────────────────────────────────────────────────────────

DROP INDEX IF EXISTS clients_phone_idx;

CREATE UNIQUE INDEX IF NOT EXISTS clients_phone_idx
  ON clients (right(regexp_replace(phone, '\D', '', 'g'), 9))
  WHERE phone <> '';
