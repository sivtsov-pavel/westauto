-- ─────────────────────────────────────────────────────────────────────────────
-- 009 — учебные данные опознаются флагом, а не текстом в заметках
--
-- До сих пор единственной приметой учебной записи была строка в notes
-- («УЧЕБНЫЕ ДАННЫЕ — …»). Этого мало по двум причинам.
--
-- Первая: заметку правит человек. Стоит заказчику дописать в карточку своё,
-- и запись перестаёт опознаваться — а скрипт, который ищет по тексту, либо
-- её пропустит, либо зацепит лишнюю.
--
-- Вторая, из-за которой миграция и появилась: учебные данные нужны и на
-- демо-стендах, и на боевом стенде заказчика — он на них учился. Удалять их
-- нельзя. А заказчик уже привязал НАСТОЯЩУЮ сделку к учебному клиенту, и
-- `demo-deals.sh remove` снёс бы эту сделку вместе с клиентом по каскаду.
-- Значит учебные записи надо не удалять, а уметь скрывать — для этого нужен
-- флаг, по которому фильтрует запрос, а не текст, по которому фильтрует LIKE.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE clients      ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;
ALTER TABLE deals        ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;
ALTER TABLE leads        ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;
ALTER TABLE calculations ADD COLUMN IF NOT EXISTS is_demo boolean NOT NULL DEFAULT false;

-- ─── Разметка того, что уже лежит в базе ─────────────────────────────────────
--
-- Помечаем ТОЛЬКО по собственной метке записи — префиксу в заметках, который
-- ставит demo-deals.sh. Ни одного условия «по связи» здесь нет намеренно.
--
-- Соблазн пометить сделки через `client_id IN (учебные клиенты)` велик и
-- неверен: ровно так и выглядит уже случившаяся беда — к учебному клиенту
-- привязана настоящая сделка. Пометив её, мы спрятали бы от заказчика живые
-- деньги, и он узнал бы об этом не из интерфейса, а от клиента.
--
-- Цена выбранной осторожности известна и невелика: учебная запись, которой
-- переписали заметку, останется непомеченной и будет видна. Это заметно
-- глазами и правится одной строкой руками. Обратная ошибка — спрятанная
-- настоящая сделка — не заметна вообще.

UPDATE clients SET is_demo = true
 WHERE NOT is_demo AND notes LIKE 'УЧЕБНЫЕ ДАННЫЕ%';

UPDATE deals SET is_demo = true
 WHERE NOT is_demo AND notes LIKE 'УЧЕБНЫЕ ДАННЫЕ%';

-- У заявки своё поле для текста — comment, а не notes
UPDATE leads SET is_demo = true
 WHERE NOT is_demo AND comment LIKE 'УЧЕБНЫЕ ДАННЫЕ%';

-- Расчёты учебными не заводились ни разу: demo-deals.sh их не создаёт, а
-- колонки для заметок у calculations нет вовсе — опознать нечего. Колонка
-- добавлена, чтобы фильтр был единым для всех четырёх списков и чтобы
-- будущему наполнению стенда было куда ставить флаг.

-- ─── Индексы под фильтр ──────────────────────────────────────────────────────
--
-- Частичные и именно по `NOT is_demo`: запросы спрашивают «покажи живые»,
-- а не «покажи учебные». Индекс `WHERE is_demo` такому запросу бесполезен.
--
-- На боевом стенде выигрыш скромный — учебных записей там десятки. Платят
-- эти индексы за себя на демо-стендах, где всё наоборот: учебного почти
-- всё, живого почти ничего, и «живые по дате» — это крошечный индекс вместо
-- прохода по всей таблице.

CREATE INDEX IF NOT EXISTS clients_live_idx      ON clients      (created_at DESC) WHERE NOT is_demo;
CREATE INDEX IF NOT EXISTS deals_live_idx        ON deals        (created_at DESC) WHERE NOT is_demo;
CREATE INDEX IF NOT EXISTS leads_live_idx        ON leads        (created_at DESC) WHERE NOT is_demo;
CREATE INDEX IF NOT EXISTS calculations_live_idx ON calculations (created_at DESC) WHERE NOT is_demo;

-- ─── Настройка видимости ─────────────────────────────────────────────────────
--
-- 0 — показывать учебные записи (прежнее поведение системы), 1 — скрывать.
-- Значение по умолчанию прописано и здесь, и в seedDefaultSettings: миграция
-- заводит его сразу, чтобы на уже работающем стенде настройка появилась в
-- том же шаге, а не при следующем старте приложения.

INSERT INTO settings (key, value) VALUES ('hide_demo_data', 0)
ON CONFLICT (key) DO NOTHING;
