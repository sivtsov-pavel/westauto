-- 004 — другие аукционные площадки
--
-- ТЗ просило «архитектуру с заделом под другие площадки без переписывания
-- ядра». Ядро действительно не трогаем: расширяем перечисление, и тарифы,
-- расчёты, витрина и наблюдение начинают работать с новыми площадками как
-- есть. Разбор страниц лотов у каждой площадки свой — он в адаптерах.
--
-- ALTER TYPE ... ADD VALUE допустим внутри транзакции начиная с PostgreSQL 12,
-- пока новое значение не используется в той же транзакции. Мы его только
-- объявляем, поэтому миграция проходит одним куском.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TYPE platform ADD VALUE IF NOT EXISTS 'copart_uk';
ALTER TYPE platform ADD VALUE IF NOT EXISTS 'copart_ca';
ALTER TYPE platform ADD VALUE IF NOT EXISTS 'iaai_ca';
ALTER TYPE platform ADD VALUE IF NOT EXISTS 'manheim';
