-- Принудительная смена пароля при первом входе.
--
-- Пароль, который придумали не вы, знает как минимум ещё один человек — тот,
-- кто его придумал и передал. Пока он не сменён, «кто сделал» в журнале правок
-- значит меньше, чем кажется: под этим логином может работать кто угодно из
-- тех, через чьи руки прошёл пароль.
--
-- Поэтому новый пользователь и сброс пароля администратором помечают учётную
-- запись: до смены пароля система не пускает дальше экрана смены.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;

-- Существующим учётным записям флаг не ставим: люди уже работают, и внезапный
-- экран смены пароля посреди рабочего дня выглядел бы как поломка. Правило
-- действует для тех, кого заводят после этой миграции.
