import { HttpError } from './errors.js';

/**
 * Пароль, который придумали не вы, знает как минимум ещё один человек — тот,
 * кто его придумал и передал. Пока он не сменён, запись в журнале правок «кто
 * сделал» значит меньше, чем кажется.
 *
 * Логика вынесена отдельно от auth.ts намеренно: там при импорте проверяются
 * переменные окружения (адрес базы, секрет подписи), и правило, которое ни от
 * чего из этого не зависит, иначе нельзя было бы проверить тестом.
 */

/**
 * Пути, доступные до смены выданного пароля.
 *
 * Всё остальное закрыто: иначе обязательная смена обходится тем, что человек
 * просто не нажимает кнопку и продолжает работать под паролем, который знает
 * ещё кто-то. Выход и чтение своего профиля оставлены — без них человек
 * оказался бы в тупике, из которого не выйти даже кнопкой «выйти».
 */
export const ALLOWED_BEFORE_PASSWORD_CHANGE: ReadonlySet<string> = new Set([
  '/api/auth/me',
  '/api/auth/change-password',
  '/api/auth/logout',
]);

export const PASSWORD_CHANGE_REQUIRED = 'password_change_required';

/**
 * Держит пользователя на экране смены пароля.
 *
 * Отдаёт 403 с кодом: по тексту сообщения интерфейс отличать случаи не может,
 * разбор текста ломается при первой же правке формулировки.
 */
export function assertPasswordChanged(
  request: { url: string },
  user: { mustChangePassword: boolean },
): void {
  if (!user.mustChangePassword) return;

  // Путь сравниваем без строки запроса: иначе «/api/deals?stage=lead»
  // не совпал бы ни с одним правилом и прошёл бы мимо проверки
  const path = request.url.split('?')[0] ?? '';
  if (ALLOWED_BEFORE_PASSWORD_CHANGE.has(path)) return;

  throw new HttpError(403, 'Сначала смените выданный пароль', {
    code: PASSWORD_CHANGE_REQUIRED,
  });
}
